CREATE TABLE public.provinces (
	province_name varchar(100) NOT NULL,
	CONSTRAINT provinces_pkey PRIMARY KEY (province_name)
);

CREATE TABLE public.localities (
	locality_name varchar(100) NOT NULL,
	province_name varchar(100) NOT NULL,
	CONSTRAINT localities_pkey PRIMARY KEY (locality_name)
);
CREATE INDEX idx_localities_province ON public.localities USING btree (province_name);

ALTER TABLE public.localities ADD CONSTRAINT localities_province_name_fkey FOREIGN KEY (province_name) REFERENCES public.provinces(province_name) ON DELETE RESTRICT ON UPDATE CASCADE;

CREATE TABLE public.model_types (
	model_type_id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
	locality_name varchar(100) NOT NULL,
	model_type_code varchar(100) NOT NULL,
	CONSTRAINT model_types_pkey PRIMARY KEY (model_type_id)
);
CREATE INDEX idx_model_types_locality ON public.model_types USING btree (locality_name);
CREATE UNIQUE INDEX uq_locality_model_type ON public.model_types USING btree (locality_name, model_type_code);

ALTER TABLE public.model_types ADD CONSTRAINT model_types_locality_name_fkey FOREIGN KEY (locality_name) REFERENCES public.localities(locality_name) ON DELETE RESTRICT ON UPDATE CASCADE;

CREATE TABLE public.model_artifacts (
	artifact_id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
	model_type_id int8 NOT NULL,
	artifact_type varchar(100) NOT NULL,
	file_name varchar(255) NOT NULL,
	artifact_data bytea NOT NULL,
	sha256 bpchar(64) NOT NULL,
	CONSTRAINT model_artifacts_pkey PRIMARY KEY (artifact_id)
);
CREATE INDEX idx_model_artifacts_model ON public.model_artifacts USING btree (model_type_id);
CREATE UNIQUE INDEX uq_model_artifact_type ON public.model_artifacts USING btree (model_type_id, artifact_type);

ALTER TABLE public.model_artifacts ADD CONSTRAINT model_artifacts_model_type_id_fkey FOREIGN KEY (model_type_id) REFERENCES public.model_types(model_type_id) ON DELETE CASCADE;